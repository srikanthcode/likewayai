// Files are persisted to MongoDB (via file-store) and served from
// /api/files/[id]. Writing to public/outputs breaks on Vercel serverless
// (read-only FS) and runtime-written public files are not served by Next.

function safeFilename(name: string, ext: string): string {
  let base = name.replace(/[^a-zA-Z0-9._\- ]/g, "").trim().slice(0, 80) || `document-${Date.now()}`;
  if (!base.toLowerCase().endsWith("." + ext)) base += "." + ext;
  return base;
}

function downloadLink(url: string, filename: string): string {
  return `**File ready:** [${filename}](${url})`;
}

/** Extract a JSON value (array/object) from LLM text output, leniently. */
function extractJson(text: string): any | null {
  const trimmed = text.trim();
  try {
    return JSON.parse(trimmed);
  } catch {}
  const fence = trimmed.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) {
    try {
      return JSON.parse(fence[1].trim());
    } catch {}
  }
  const arrMatch = trimmed.match(/\[[\s\S]*\]/);
  if (arrMatch) {
    try {
      return JSON.parse(arrMatch[0]);
    } catch {}
  }
  return null;
}

