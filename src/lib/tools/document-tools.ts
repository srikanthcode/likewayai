export const createDocxTool = createTool(
  {
    name: "CREATE_DOCX",
    description: "Create a professional Word document (DOCX) with headings, paragraphs, tables, and lists.",
    category: "document",
    parameters: [
      { name: "title", type: "string", description: "Document title", required: true },
      { name: "content", type: "string", description: "Markdown content to convert to DOCX", required: true },
      { name: "filename", type: "string", description: "Output filename (e.g., report.docx)", required: false, default: "output.docx" },
    ],
    permissions: ["write", "filesystem"],
    cost: { tokens: 1000, credits: 1, money: 0.001 },
    timeout: 30000,
    retryable: false,
    examples: ["Create a business proposal as a Word document"],
  },
  async (params, context) => {
    const startTime = Date.now();
    try {
      const title = String(params.title || "Document");
      const content = String(params.content || "");
      const filename = safeFilename(String(params.filename || `likeway-${Date.now()}`), "docx");

      const children: any[] = [];

      // Title
      children.push(
        new Paragraph({
          children: [new TextRun({ text: title, bold: true, size: 48 })],
          heading: HeadingLevel.TITLE,
          alignment: AlignmentType.CENTER,
        })
      );

      // Parse content
      const lines = content.split("\n");
      for (const line of lines) {
        if (line.startsWith("# ")) {
          children.push(
            new Paragraph({
              children: [new TextRun({ text: line.slice(2), bold: true, size: 36 })],
              heading: HeadingLevel.HEADING_1,
            })
          );
        } else if (line.startsWith("## ")) {
          children.push(
            new Paragraph({
              children: [new TextRun({ text: line.slice(3), bold: true, size: 30 })],
              heading: HeadingLevel.HEADING_2,
            })
          );
        } else if (line.startsWith("### ")) {
          children.push(
            new Paragraph({
              children: [new TextRun({ text: line.slice(4), bold: true, size: 26 })],
              heading: HeadingLevel.HEADING_3,
            })
          );
        } else if (line.startsWith("- ")) {
          children.push(
            new Paragraph({
              children: [new TextRun({ text: `• ${line.slice(2)}`, size: 22 })],
              bullet: { level: 0 },
            })
          );
        } else if (line.trim() === "") {
          children.push(new Paragraph({ children: [] }));
        } else {
          // Handle bold and italic
          const runs = parseInlineFormatting(line);
          children.push(
            new Paragraph({
              children: runs,
              spacing: { after: 120 },
            })
          );
        }
      }

      const doc = new Document({
        sections: [{ children }],
      });

      const buffer = await Packer.toBuffer(doc);
      const stored = await saveGeneratedFile(
        context.userId,
        context.projectId,
        filename,
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        Buffer.from(buffer)
      );

      return {
        success: true,
        data: `${downloadLink(stored.url, filename)}\n\nSize: ${(stored.size / 1024).toFixed(0)} KB · Format: DOCX (editable in Word/Google Docs)`,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0, fileId: stored.id, fileUrl: stored.url },
      };
    } catch (error: any) {
      return {
        success: false,
        error: error.message,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0 },
      };
    }
  }
);

