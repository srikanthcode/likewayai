export const createPptxTool = createTool(
  {
    name: "CREATE_PPTX",
    description: "Create a PowerPoint presentation with slides, text, images, and charts.",
    category: "document",
    parameters: [
      { name: "title", type: "string", description: "Presentation title", required: true },
      { name: "slides", type: "array", description: "Array of slide objects with title and content", required: true },
      { name: "filename", type: "string", description: "Output filename (e.g., presentation.pptx)", required: false, default: "output.pptx" },
    ],
    permissions: ["write", "filesystem"],
    cost: { tokens: 1500, credits: 2, money: 0.002 },
    timeout: 30000,
    retryable: false,
    examples: ["Create a 10-slide business pitch deck"],
  },
  async (params, context) => {
    const startTime = Date.now();
    try {
      const title = String(params.title || "Presentation");
      const slides = Array.isArray(params.slides) ? params.slides : [];
      const filename = safeFilename(String(params.filename || `likeway-${Date.now()}`), "pptx");

      const pptx = new PptxGenJS();
      pptx.title = title;
      pptx.author = "LikeWay AI";

      // Title slide
      const titleSlide = pptx.addSlide();
      titleSlide.addText(title, {
        x: 0.5, y: 2, w: 9, h: 1,
        fontSize: 32, bold: true, align: "center", color: "1F2937",
      });

      // Content slides
      for (const slide of slides) {
        const s = pptx.addSlide();
        s.addText(slide.title || "", { x: 0.5, y: 0.3, w: 9, h: 0.8, fontSize: 24, bold: true, color: "1F2937" });

        if (typeof slide.content === "string") {
          s.addText(slide.content, { x: 0.5, y: 1.3, w: 9, h: 4.5, fontSize: 14, color: "374151" });
        } else if (Array.isArray(slide.content)) {
          let y = 1.3;
          for (const item of slide.content) {
            s.addText(`• ${item}`, { x: 0.5, y, w: 9, h: 0.4, fontSize: 14, color: "374151" });
            y += 0.45;
          }
        }
      }

      // Thank you slide
      const thankYou = pptx.addSlide();
      thankYou.addText("Thank You", { x: 0, y: 2, w: "100%", h: 1.5, fontSize: 36, bold: true, align: "center", color: "1F2937" });
      thankYou.addText(`Generated by LikeWay AI | ${new Date().toLocaleDateString()}`, { x: 0, y: 3.5, w: "100%", h: 0.5, fontSize: 12, align: "center", color: "9CA3AF" });

      const pptxBuffer = await pptx.write({ outputType: "nodebuffer" });
      const stored = await saveGeneratedFile(
        context.userId,
        context.projectId,
        filename,
        "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        Buffer.from(pptxBuffer as unknown as Uint8Array)
      );

      return {
        success: true,
        data: `${downloadLink(stored.url, filename)}\n\nSlides: ${slides.length + 2} · Format: PPTX`,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0, fileId: stored.id, fileUrl: stored.url },
      };
    } catch (error: any) {
      return {
        success: false,
        error: error.message,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0 },
      };
    }
  }
);

