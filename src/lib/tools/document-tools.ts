// PDF GENERATION TOOL
// ══════════════════════════════════════════════════════════════════════

export const createPdfTool = createTool(
  {
    name: "CREATE_PDF",
    description: "Create a professional PDF document with formatted text, headings, tables, and lists.",
    category: "document",
    parameters: [
      { name: "title", type: "string", description: "Document title", required: true },
      { name: "content", type: "string", description: "Markdown content to render in PDF", required: true },
      { name: "filename", type: "string", description: "Output filename (e.g., report.pdf)", required: false, default: "output.pdf" },
    ],
    permissions: ["write", "filesystem"],
    cost: { tokens: 1000, credits: 1, money: 0.001 },
    timeout: 30000,
    retryable: false,
    examples: ["Create a PDF report with executive summary and data analysis"],
  },
  async (params, context) => {
    const startTime = Date.now();
    try {
      const title = String(params.title || "Document");
      const content = String(params.content || "");
      const filename = safeFilename(String(params.filename || `likeway-${Date.now()}`), "pdf");

      const doc = new PDFDocument({ margin: 50, size: "A4" });
      const chunks: Buffer[] = [];
      doc.on("data", (c: Buffer) => chunks.push(c));
      const pdfDone = new Promise<void>((resolve, reject) => {
        doc.on("end", () => resolve());
        doc.on("error", reject);
      });

      // Title
      doc.fontSize(24).font("Helvetica-Bold").text(title, { align: "center" });
      doc.moveDown(2);

      // Parse markdown-like content
      const lines = content.split("\n");
      for (const line of lines) {
        if (line.startsWith("# ")) {
          doc.fontSize(20).font("Helvetica-Bold").text(line.slice(2));
          doc.moveDown(0.5);
        } else if (line.startsWith("## ")) {
          doc.fontSize(16).font("Helvetica-Bold").text(line.slice(3));
          doc.moveDown(0.3);
        } else if (line.startsWith("### ")) {
          doc.fontSize(13).font("Helvetica-Bold").text(line.slice(4));
          doc.moveDown(0.2);
        } else if (line.startsWith("- ")) {
          doc.fontSize(11).font("Helvetica").text(`  • ${line.slice(2)}`, { continued: false });
        } else if (line.startsWith("|")) {
          // Table row - render as formatted text
          const cells = line.split("|").filter(c => c.trim()).map(c => c.trim());
          doc.fontSize(10).font("Courier").text(cells.join("  |  "));
        } else if (line.trim() === "") {
          doc.moveDown(0.5);
        } else {
          doc.fontSize(11).font("Helvetica").text(line);
        }
      }

      // Footer
      doc.fontSize(8).font("Helvetica-Oblique")
        .text(`Generated by LikeWay AI | ${new Date().toLocaleDateString()}`, 50, doc.page.height - 50, { align: "center" });

      doc.end();
      await pdfDone;

      const bytes = Buffer.concat(chunks);
      const stored = await saveGeneratedFile(
        context.userId,
        context.projectId,
        filename,
        "application/pdf",
        bytes
      );

      return {
        success: true,
        data: `${downloadLink(stored.url, filename)}\n\nSize: ${(stored.size / 1024).toFixed(0)} KB · Format: PDF`,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0, fileId: stored.id, fileUrl: stored.url },
      };
    } catch (error: any) {
      return {
        success: false,
        error: error.message,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0 },
      };
    }
  }
);

