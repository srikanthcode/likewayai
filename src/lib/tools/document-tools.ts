export const createXlsxTool = createTool(
  {
    name: "CREATE_XLSX",
    description: "Create an Excel spreadsheet with data, formulas, formatting, and charts.",
    category: "document",
    parameters: [
      { name: "title", type: "string", description: "Sheet name or workbook title", required: true },
      { name: "headers", type: "array", description: "Column headers array", required: true },
      { name: "rows", type: "array", description: "2D array of row data", required: true },
      { name: "filename", type: "string", description: "Output filename (e.g., report.xlsx)", required: false, default: "output.xlsx" },
    ],
    permissions: ["write", "filesystem"],
    cost: { tokens: 1000, credits: 1, money: 0.001 },
    timeout: 30000,
    retryable: false,
    examples: ["Create a sales report spreadsheet with charts"],
  },
  async (params, context) => {
    const startTime = Date.now();
    try {
      const title = String(params.title || "Data");
      const filename = safeFilename(String(params.filename || `likeway-${Date.now()}`), "xlsx");

      let headers: any[] = Array.isArray(params.headers) ? params.headers : [];
      let rows: any[][] = Array.isArray(params.rows) ? params.rows : [];

      // Lenient mode: accept a JSON payload string in `rows` (typical when the
      // rows come from a prior LLM planning step via {{step:id}} templating).
      // Supports array-of-objects (keys become headers) and 2D arrays.
      if (!Array.isArray(params.rows) && params.rows != null) {
        const parsed = extractJson(String(params.rows));
        if (Array.isArray(parsed) && parsed.length > 0) {
          const first = parsed[0];
          if (!Array.isArray(first) && typeof first === "object" && first !== null) {
            const keys = Object.keys(first);
            headers = headers.length > 0 ? headers : keys;
            rows = parsed.map((r: any) => keys.map((k) => r[k] ?? ""));
          } else if (Array.isArray(first)) {
            rows = parsed;
          } else {
            headers = ["Value"];
            rows = parsed.map((v: any) => [v]);
          }
        }
      }

      if (rows.length === 0) {
        return { success: false, error: "No valid rows provided. Pass a 2D array, array of objects, or a JSON string." };
      }

      const workbook = new ExcelJS.Workbook();
      const sheet = workbook.addWorksheet(title);

      // Add headers with styling
      const headerRow = sheet.addRow(headers);
      headerRow.eachCell((cell) => {
        cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF3B82F6" } };
        cell.alignment = { horizontal: "center" };
        cell.border = {
          top: { style: "thin" },
          bottom: { style: "thin" },
          left: { style: "thin" },
          right: { style: "thin" },
        };
      });

      // Add data rows
      for (const row of rows) {
        const dataRow = sheet.addRow(row);
        dataRow.eachCell((cell) => {
          cell.border = {
            top: { style: "thin" },
            bottom: { style: "thin" },
            left: { style: "thin" },
            right: { style: "thin" },
          };
        });
      }

      // Auto-fit columns
      sheet.columns.forEach((col) => {
        const maxLen = Math.max(
          col.header?.toString().length || 0,
          ...col.values?.map(v => String(v).length) || [0]
        );
        col.width = Math.min(maxLen + 2, 30);
      });

      // Add summary row if numeric data
      if (rows.length > 0 && typeof rows[0][rows[0].length - 1] === "number") {
        const summaryRow = sheet.addRow(["Total", ...Array(headers.length - 2).fill(""), rows.reduce((sum: number, r: any) => sum + (Number(r[r.length - 1]) || 0), 0)]);
        summaryRow.font = { bold: true };
      }

      const xlsxBuffer = await workbook.xlsx.writeBuffer();
      const stored = await saveGeneratedFile(
        context.userId,
        context.projectId,
        filename,
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        Buffer.from(xlsxBuffer as ArrayBuffer)
      );

      return {
        success: true,
        data: `${downloadLink(stored.url, filename)}\n\nRows: ${rows.length + 1} (incl. header) · Format: XLSX`,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0, fileId: stored.id, fileUrl: stored.url },
      };
    } catch (error: any) {
      return {
        success: false,
        error: error.message,
        metadata: { duration: Date.now() - startTime, tokensUsed: 0 },
      };
    }
  }
);

